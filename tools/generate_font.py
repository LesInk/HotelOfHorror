def glyph_from_pattern(pattern):
    pen = TTGlyphPen(None)
    if pattern:
        for row, line in enumerate(pattern):
            y = (6 - row) * 100
            for col, bit in enumerate(line):
                if bit == "1":
                    x = col * 100 + 50
                    pen.moveTo((x, y))
                    pen.lineTo((x + 90, y))
                    pen.lineTo((x + 90, y + 90))
                    pen.lineTo((x, y + 90))
                    pen.closePath()
    return pen.glyph()


def main():
    output = Path(__file__).resolve().parents[1] / "assets" / "hotel-zx81.ttf"
    output.parent.mkdir(parents=True, exist_ok=True)

    glyph_order = [".notdef", "space"]
    char_to_glyph = {}
    glyphs = {".notdef": glyph_from_pattern(["11111", "10001", "10101", "10001", "10101", "10001", "11111"]), "space": glyph_from_pattern(None)}

    for char, pattern in PATTERNS.items():
        name = f"uni{ord(char):04X}"
        glyph_order.append(name)
        glyphs[name] = glyph_from_pattern(pattern)
        char_to_glyph[ord(char)] = name

    char_to_glyph[32] = "space"

    builder = FontBuilder(800, isTTF=True)
    builder.setupGlyphOrder(glyph_order)
    builder.setupCharacterMap(char_to_glyph)
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({name: (650, 0) for name in glyph_order})
    builder.setupHorizontalHeader(ascent=800, descent=-100)
    builder.setupNameTable({
        "familyName": "Hotel ZX81",
        "styleName": "Regular",
        "uniqueFontIdentifier": "Hotel of Horror ZX81 1.0",
        "fullName": "Hotel ZX81 Regular",
        "psName": "HotelZX81-Regular",
        "version": "Version 1.0",
    })
    builder.setupOS2(sTypoAscender=800, sTypoDescender=-100, usWinAscent=800, usWinDescent=100)
    builder.setupPost()
    builder.setupMaxp()
    builder.save(output)
    print(output)


if __name__ == "__main__":
    main()
